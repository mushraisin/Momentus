/** Переклад із підстановкою змінних {name}. */
export function t(lang, key, vars) {
  const l = DICT[lang] ? lang : DEFAULT_LANG;
  let s = DICT[l][key] ?? DICT[DEFAULT_LANG][key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

/** Валідна мова або дефолт. Знята мова (напр. ru) тихо стає українською. */
export function normalizeLang(value) {
  const v = String(value ?? '').toLowerCase().slice(0, 2);
  return LANGS[v] ? v : DEFAULT_LANG;
}

/** Мова з Accept-Language браузера. */
export function langFromHeader(header) {
  const raw = String(header ?? '').toLowerCase();
  for (const part of raw.split(',')) {
    const code = part.split(';')[0].trim().slice(0, 2);
    if (LANGS[code]) return code;
  }
  return DEFAULT_LANG;
}
